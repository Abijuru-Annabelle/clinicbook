CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(100) NOT NULL,
    email         VARCHAR(150) NOT NULL UNIQUE,
    phone         VARCHAR(20),
    password_hash VARCHAR(255),
    provider      VARCHAR(10)  NOT NULL DEFAULT 'LOCAL' CHECK (provider IN ('LOCAL','GOOGLE')),
    role          VARCHAR(10)  NOT NULL CHECK (role IN ('PATIENT','DOCTOR','ADMIN')),
    enabled       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMP    NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS departments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    description VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS patients (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    date_of_birth DATE,
    gender        VARCHAR(10) CHECK (gender IN ('MALE','FEMALE')),
    address       VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS doctors (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
    department_id  BIGINT NOT NULL REFERENCES departments(id),
    specialization VARCHAR(100) NOT NULL,
    license_number VARCHAR(50)  NOT NULL UNIQUE,
    slot_minutes   INT NOT NULL DEFAULT 30 CHECK (slot_minutes BETWEEN 10 AND 120)
);

CREATE TABLE IF NOT EXISTS availability (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doctor_id   BIGINT   NOT NULL REFERENCES doctors(id) ON DELETE CASCADE,
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time  TIME     NOT NULL,
    end_time    TIME     NOT NULL,
    CHECK (end_time > start_time),
    UNIQUE (doctor_id, day_of_week, start_time)
);

CREATE TABLE IF NOT EXISTS appointments (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id BIGINT NOT NULL REFERENCES patients(id),
    doctor_id  BIGINT NOT NULL REFERENCES doctors(id),
    start_time TIMESTAMP NOT NULL,
    end_time   TIMESTAMP NOT NULL,
    status     VARCHAR(10) NOT NULL DEFAULT 'BOOKED'
               CHECK (status IN ('BOOKED','COMPLETED','CANCELLED','NO_SHOW')),
    reason     VARCHAR(255),
    notes      TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMP NOT NULL DEFAULT NOW(),
    CHECK (end_time > start_time)
);

-- Prevents double booking; cancelled appointments free the slot
CREATE UNIQUE INDEX IF NOT EXISTS uq_doctor_active_slot
    ON appointments (doctor_id, start_time)
    WHERE status <> 'CANCELLED';

CREATE INDEX IF NOT EXISTS idx_appt_patient_time ON appointments (patient_id, start_time);
CREATE INDEX IF NOT EXISTS idx_appt_doctor_time  ON appointments (doctor_id, start_time);
CREATE INDEX IF NOT EXISTS idx_doctors_dept      ON doctors (department_id);
